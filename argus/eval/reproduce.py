"""R4-d: one command rebuilds every results table and figure from committed inputs (ADR-0013).

    python -m argus.eval.reproduce            → docs/results/*.md, *.csv, figures/*.svg   (≈ 12 min)
    python -m argus.eval.reproduce --fast     → same, but the R1b grid table is left as committed (≈ 3 min)
    python -m argus.eval.reproduce --check    → rebuild in a temp dir; exit 1 if anything differs

Offline: no network, no API keys. Inputs are the committed benchmark files, the R2-L
response caches and run logs (eval/r2l/), and the frozen configs. Numbers are rounded to
fixed decimals so the output is byte-stable. Latency tables are machine-dependent and are
written separately by `python -m argus.eval.latency` (docs/results/latency-*.md); never checked here.
"""

from __future__ import annotations

import argparse
import csv
import difflib
import io
import json
import tempfile
from pathlib import Path
from typing import Any

from argus.eval import poc, r1b, r3, r4
from argus.eval.svg import histogram, line_chart

ROOT = r3.ROOT
RESULTS = ROOT / "docs" / "results"
R2L_DIR = ROOT / "eval" / "r2l"
HEADER = "<!-- Generated by `python -m argus.eval.reproduce`. Do not edit by hand. -->\n"


def f3(x: Any) -> str:
    if x is None:
        return "–"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, float):
        return f"{x:.3f}"
    return str(x)


def pct(x: Any) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def table(head: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def rounded(o: Any, nd: int = 6) -> Any:
    """Floats rounded so the app's JSON is byte-stable across operating systems."""
    if isinstance(o, float):
        return round(o, nd)
    if isinstance(o, dict):
        return {k: rounded(v, nd) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [rounded(v, nd) for v in o]
    return o


def as_json(o: Any) -> str:
    return json.dumps(rounded(o), indent=1, sort_keys=True, ensure_ascii=True) + "\n"


def r2l_summaries() -> list[dict[str, Any]]:
    return [json.loads(f.read_text(encoding="utf-8"))["summary"] for f in sorted(R2L_DIR.glob("*/*.json"))]


def ci(c: list[float] | None) -> str:
    return "–" if not c else f"[{c[0]:.3f}, {c[1]:.3f}]"


# ------------------------------------------------------------- renderers

def render_r1b(sel: dict[str, Any]) -> str:
    rows = []
    for name, r in sel["results"].items():
        a = r["agg"]
        m = lambda k: a[k]["mean"] if k in a and a[k]["mean"] is not None else None  # noqa: E731
        rows.append([("**" + name + "**") if name == sel["selection"]["selected"] else name,
                     pct(m("nested_fpr")), f3(m("auroc")), f3(m("auroc_compliant")), pct(m("dr")),
                     pct(m("dr_visible")), pct(m("dr_compliant"))])
    return (HEADER + "# R1b dev selection (ADR-0007)\n\nDev only, leave-one-intent-out calibration, nested FPR. "
            f"Selected: **{sel['selection']['selected']}** ({sel['selection']['reason']}).\n\n"
            + table(["Config", "Nested FPR", "AUROC", "AUROC compliant", "DR", "DR visible", "DR compliant"], rows))


def render_r2l() -> str:
    rows = []
    for f in sorted(R2L_DIR.glob("*/*.json")):
        s = json.loads(f.read_text(encoding="utf-8"))["summary"]
        lat = s.get("latency_ms") or {}
        eb = s.get("escalate_or_block") or {}
        rows.append([s["run"], s["model"], s["judged"], pct(s.get("valid_json_rate")),
                     f3(s.get("auroc_unsafe_vs_benign")), eb.get("unsafe", "–"), eb.get("benign", "–"),
                     f"{lat.get('p50', 0) / 1000:.1f} / {lat.get('p95', 0) / 1000:.1f}" if lat else "–"])
    return (HEADER + "# R2-L local LLM monitor runs (ADR-0011)\n\nFrom the run logs the GitHub workflow committed under "
            "`eval/r2l/` (Ollama 0.40.2, CPU runner, $0).\n\n"
            + table(["Run", "Model", "Judged", "Valid JSON", "AUROC", "ESC/BLOCK unsafe", "ESC/BLOCK benign",
                     "p50 / p95 s"], rows))


def render_r3(d: dict[str, Any]) -> str:
    comp = d["components_at_budget"]
    rows = [[k, pct(v["dr"]), pct(v["dr_visible"]), pct(v["dr_compliant"]), pct(v["fpr"])] for k, v in comp.items()]
    abl = [[k, pct(v["dr"]), pct(v["dr_compliant"]), pct(v["fpr"])] for k, v in d["ablations"].items()]
    lv = d["levels"]
    return (HEADER + "# R3 dev report tables (ADR-0012)\n\nDev, leave-one-template-out. Narrative: "
            "`docs/R3_DEV_REPORT.md`.\n\n"
            f"Levels (risk points): MEDIUM > {lv['medium']:.2f}, HIGH > {lv['high']:.2f}, "
            f"CRITICAL > {lv['critical']:.2f}.\n\n"
            + table(["Component", "DR", "DR visible", "DR compliant", "Benign FPR"], rows) + "\n## Ablations\n\n"
            + table(["Variant", "DR", "DR compliant", "FPR"], abl)
            + f"\nFrozen files reproduced by this rerun: "
              f"{', '.join(k for k, v in d['frozen'].items() if v['rerun_reproduces']) or 'none'}.\n")


def render_r4(rep: dict[str, Any]) -> tuple[str, str]:
    d = rep["dev"]
    m = d["methods"]
    rows = [[k, pct(v["dr"]), pct(v["dr_in_time"]), pct(v["dr_visible"]), pct(v["dr_compliant"]), pct(v["fpr"]),
             pct(v["fpr_step"]), f3(v["precision"]), f3(v["f1"]), f3(v.get("prefix_auroc")),
             f3(v["earliness"]["mean_steps_before_harm"]), f3(v["earliness"].get("mean_steps_earlier_than_rules"))]
            for k, v in m.items()]
    cis = [[k, ci(v["ci95"]["dr"]), ci(v["ci95"]["fpr"])] for k, v in m.items() if "ci95" in v]
    paired = [[k, v["only_a"], v["only_b"], v["n"], f"{v['p']:.4f}", f"{v['p_holm']:.4f}"] for k, v in d["paired"].items()]
    cont = [[k, pct(v["harm_completion"]), pct(v["attack_progress_prevented"]), pct(v["post_onset_steps_executed"]),
             f3(v["mean_steps_to_containment"]), f"{v['approvals_per_100_benign']:.1f}", pct(v["benign_quarantined"]),
             pct(v["benign_disrupted"])] for k, v in d["containment"].items()]
    lofo = [[k, pct(v["dr"]), pct(v["dr_compliant"]), pct(v["dr_visible"]), v["n"]] for k, v in d["lofo"].items()]
    seeds = [[k, pct(v["dr"]), pct(v["fpr"])] for k, v in d["seeds"]["per_seed"].items()]
    v1 = rep["v1_test_exploratory"]
    v1rows = [[k, pct(v["dr"]), pct(v["dr_visible"]), pct(v["dr_compliant"]), pct(v["fpr"]), f3(v["f1"])]
              for k, v in v1["methods"].items()]
    g5, g6 = d["g5_preview"], d["g6_preview"]
    md = (HEADER + "# R4 dev tables (ADR-0013)\n\n"
          f"**Dev, out-of-fold, exploratory.** {d['data']['attacks']} attacks, {d['data']['benign']} benign, "
          f"{d['data']['steps']} steps. Budget: ≤ {int(100 * d['budget'])}% of dev benign trajectories flagged. "
          "The official G5/G6 verdicts come only from the single blind test-v2 run.\n\n"
          f"- G5 preview: hybrid DR {pct(g5['hybrid_dr'])} vs best component {g5['best_component']} "
          f"{pct(g5['best_component_dr'])} → {'pass' if g5['pass'] else 'fail'}.\n"
          f"- G6 preview: {g6['families_ge_50pct_compliant']}/3 held-out families ≥ 50% compliant DR → "
          f"{'pass' if g6['pass'] else 'fail'} ({g6['note']}).\n\n"
          "## Methods on identical trajectories\n\n"
          + table(["Method", "DR", "DR in time", "DR visible", "DR compliant", "FPR", "FPR/step", "Precision", "F1",
                   "Prefix AUROC", "Steps before harm", "Steps earlier than B2"], rows)
          + "\nB4_llm_native_escalate ignores the budget (reported over budget). Hybrid-no-rules removes the rule "
            "signals from the score only; a policy BLOCK stays authoritative (CRITICAL).\n\n"
          "## 95% bootstrap CIs (1,000 resamples, seed 12345, stratified)\n\n"
          + table(["Method", "DR", "FPR"], cis)
          + "\n## Paired exact McNemar (Holm-corrected)\n\n`only_a` = hybrid only, `only_b` = other only.\n\n"
          + table(["Comparison", "only_a", "only_b", "n", "p", "p (Holm)"], paired)
          + "\n## Containment (enforce mode)\n\n"
          + table(["Setting", "Harm completion", "Attack progress prevented", "Post-onset steps executed",
                   "Steps to containment", "Approvals / 100 benign", "Benign quarantined", "Benign disrupted"], cont)
          + "\nSteps to containment: first intervention minus first unsafe step (negative = before onset).\n\n"
          "## Open-set preview: frozen leave-one-family-out models on the held-out dev family\n\n"
          + table(["Held-out family", "DR", "DR compliant", "DR visible", "n"], lofo)
          + "\n## Training-resample seeds (secondary; each seed's own out-of-fold resample)\n\n"
          + table(["Seed", "DR", "FPR"], seeds)
          + f"\nMean ± std: DR {d['seeds']['dr']['mean']:.3f} ± {d['seeds']['dr']['std']:.3f}, "
            f"FPR {d['seeds']['fpr']['mean']:.3f} ± {d['seeds']['fpr']['std']:.3f}.\n\n"
          f"## Exploratory: v1 test split ({v1['split']})\n\n"
          f"{v1['data']['attacks']} attacks, {v1['data']['benign']} benign. No LLM verdicts exist for this split, so "
          "the hybrid is the frozen no-LLM ablation.\n\n"
          + table(["Method", "DR", "DR visible", "DR compliant", "FPR", "F1"], v1rows))
    buf = io.StringIO(newline="")
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["method", "dr", "dr_in_time", "dr_visible", "dr_compliant", "fpr", "fpr_step", "precision", "f1",
                "prefix_auroc", "mean_steps_before_harm", "mean_steps_earlier_than_rules", "n_attack", "n_benign"])
    for k, v in m.items():
        w.writerow([k] + [f3(v[c]) for c in ("dr", "dr_in_time", "dr_visible", "dr_compliant", "fpr", "fpr_step",
                                              "precision", "f1")]
                   + [f3(v.get("prefix_auroc")), f3(v["earliness"]["mean_steps_before_harm"]),
                      f3(v["earliness"].get("mean_steps_earlier_than_rules")), v["n_attack"], v["n_benign"]])
    return md, buf.getvalue()


def figures(rep: dict[str, Any]) -> dict[str, str]:
    d = rep["dev"]
    roc = {k: [(round(x, 4), round(y, 4)) for x, y in v] for k, v in d["roc"].items()}
    bc = d["budget_curve"]
    return {
        "r4_roc_dev.svg": line_chart("Step-level ROC (dev, out-of-fold)", "False-positive rate (benign steps)",
                                     "True-positive rate (unsafe steps)", roc, diagonal=True),
        "r4_dr_vs_budget_dev.svg": line_chart("Detection rate vs benign budget (dev)", "Benign trajectories flagged",
                                              "Attack trajectories detected",
                                              {k: list(zip(bc["budgets"], bc[k])) for k in bc if k != "budgets"},
                                              xmax=0.3, xfmt="{:.2f}"),
        "r4_earliness_dev.svg": histogram("Hybrid: steps before harm (dev, detected in time)",
                                          "Steps between first flag and harm step", "Attacks",
                                          d["earliness_hist"], "Hybrid"),
    }


# ------------------------------------------------------------------- build

def build(out: Path, fast: bool) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    (out / "figures").mkdir(exist_ok=True)
    written: list[Path] = []

    def put(name: str, text: str) -> None:
        p = out / name
        p.write_bytes(text.encode("utf-8"))
        written.append(p)

    if not fast:
        r1b.main([])
        sel = json.loads((r1b.OUT_DIR / "dev_selection.json").read_text(encoding="utf-8"))
        put("r1b_dev_selection.md", render_r1b(sel))
        put("r1b_dev_selection.json", as_json({k: v for k, v in sel.items() if k != "results"}
                                              | {"results": {n: {"config": r["config"], "agg": r["agg"]}
                                                             for n, r in sel["results"].items()}}))
    put("r2l_runs.md", render_r2l())
    put("r2l_runs.json", as_json(r2l_summaries()))
    r3.main([])
    r3_report = json.loads(r3.OUT.read_text(encoding="utf-8"))
    put("r3_dev.md", render_r3(r3_report))
    put("r3_dev.json", as_json({k: v for k, v in r3_report.items() if k != "frozen"}))
    r4.main(["dev"])
    rep = json.loads((r4.OUT_DIR / "dev.json").read_text(encoding="utf-8"))
    md, csv_text = render_r4(rep)
    put("r4_dev.md", md)
    put("r4_dev_methods.csv", csv_text)
    put("r4_dev.json", as_json(rep))
    with tempfile.TemporaryDirectory() as tmp:          # v0 PoC run, for the web app's Archive page
        put("poc_summary.json", as_json(poc.compute_summary(Path(tmp))))
    for name, svg in figures(rep).items():
        put(f"figures/{name}", svg)
    return written


def check(fast: bool) -> list[str]:
    with tempfile.TemporaryDirectory() as tmp:
        tmp_out = Path(tmp)
        written = build(tmp_out, fast)
        diffs = []
        for p in written:
            rel = p.relative_to(tmp_out).as_posix()
            ref = RESULTS / rel
            if not ref.is_file() or ref.read_bytes().replace(b"\r\n", b"\n") != p.read_bytes():
                diffs.append(rel)
                old = ref.read_text(encoding="utf-8").splitlines() if ref.is_file() else []
                lines = list(difflib.unified_diff(old, p.read_text(encoding="utf-8").splitlines(),
                                                  f"committed/{rel}", f"rebuilt/{rel}", n=0, lineterm=""))
                print("\n".join(x[:300] for x in lines[:40]))
        return diffs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fast", action="store_true", help="skip the ≈ 9 min R1b grid (its table stays as committed)")
    ap.add_argument("--check", action="store_true", help="rebuild in a temp dir and compare with docs/results/")
    args = ap.parse_args(argv)
    if args.check:
        diffs = check(args.fast)
        print("reproduce --check: " + ("OK, byte-identical" if not diffs else "DIFFERS: " + ", ".join(diffs)))
        return 0 if not diffs else 1
    for p in build(RESULTS, args.fast):
        print(f"wrote {p.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
