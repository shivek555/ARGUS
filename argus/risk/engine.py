"""R3-c/d: levels, decisions and explanations (ADR-0012, plan §4–§5).

Invariants (each tested):
* policy BLOCK → CRITICAL, always; nothing lowers it;
* non-policy signals reach CRITICAL only above τ_crit (≤ 1% of dev benign
  trajectories), otherwise at most HIGH (a human decides);
* an ML/LLM failure on a risky call floors the level at HIGH (fail closed);
* contributions + baseline == risk_points (exact).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import yaml

from argus.risk.model import RiskModel
from argus.risk.schema import LEVEL_DECISION, Contribution, RiskDecision
from argus.risk.signals import LABEL, StepSignals

# Fraction of dev benign trajectories allowed to reach each level (out-of-fold).
QUANTILES = {"medium": 0.70, "high": 0.90, "critical": 0.99}

RESPONSES: dict[str, str] = {
    "policy_block": "Blocked by policy. Review the rule hit; the call did not run.",
    "sensitive_unscoped": "Deny unless the task owner confirms secrets access; rotate the secret if it was exposed.",
    "privilege": "Deny unless the task owner confirms credential access; rotate exposed credentials.",
    "destination": "Deny the upload; confirm the destination with the task owner.",
    "persistence": "Review the diff before allowing; check it matches the objective.",
    "objective_deviation": "Confirm with the task owner that this step is part of the task.",
    "llm_escalate": "Confirm with the task owner that this step is part of the task.",
    "anomaly": "Inspect the trajectory: this sequence differs from normal benign work.",
    "data_sensitivity": "Check whether the task needs this data.",
}


@dataclass(frozen=True)
class Levels:
    medium: float
    high: float
    critical: float

    @classmethod
    def from_benign(cls, max_points_per_benign_trajectory: list[float]) -> Levels:
        q = {k: float(np.quantile(max_points_per_benign_trajectory, v, method="higher"))
             for k, v in QUANTILES.items()}
        med = q["medium"]
        high = max(q["high"], med)
        return cls(medium=med, high=high, critical=max(q["critical"], high))

    def save(self, path: Path, provenance: dict[str, object]) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        doc = {"thresholds_risk_points": {"medium": self.medium, "high": self.high, "critical": self.critical},
               "rule": {k: f"<= {int(round((1 - v) * 100))}% of dev benign trajectories reach this level "
                           "(out-of-fold, strict >)" for k, v in QUANTILES.items()},
               "provenance": provenance}
        path.write_text("# R3 risk levels (ADR-0012). Generated by `python -m argus.eval.r3`; frozen at the\n"
                        "# dev-report checkpoint. Edit only with a new ADR.\n" + yaml.safe_dump(doc, sort_keys=False),
                        encoding="utf-8")

    @classmethod
    def load(cls, path: Path) -> Levels:
        t = yaml.safe_load(path.read_text(encoding="utf-8"))["thresholds_risk_points"]
        return cls(medium=float(t["medium"]), high=float(t["high"]), critical=float(t["critical"]))


def level_for(points: float, levels: Levels, sig: StepSignals) -> tuple[str, list[str]]:
    reasons: list[str] = []
    if sig.values["policy_block"] >= 1.0:
        return "CRITICAL", [f"policy rule {sig.policy_rule or 'block'} (authoritative)"]
    if points > levels.critical:
        lvl = "CRITICAL"
        reasons.append(f"risk {points:.1f} > critical threshold {levels.critical:.1f}")
    elif points > levels.high:
        lvl = "HIGH"
        reasons.append(f"risk {points:.1f} > high threshold {levels.high:.1f}")
    elif points > levels.medium:
        lvl = "MEDIUM"
        reasons.append(f"risk {points:.1f} > medium threshold {levels.medium:.1f}")
    else:
        lvl = "LOW"
    if sig.errors and sig.risky and lvl in ("LOW", "MEDIUM"):
        lvl = "HIGH"
        reasons.append("fail closed: " + ", ".join(sig.errors))
    return lvl, reasons


def recommended_response(level: str, contributions: list[Contribution]) -> str:
    if level == "LOW":
        return "Allow: consistent with the objective."
    if level == "MEDIUM":
        return "Allow and monitor the rest of this trajectory."
    for c in contributions:
        if c.points > 0 and c.signal in RESPONSES:
            return RESPONSES[c.signal]
    return "Review before allowing."


@dataclass
class RiskEngine:
    model: RiskModel
    levels: Levels

    def decide(self, sig: StepSignals, step: int, tool: str) -> RiskDecision:
        x = sig.vector(self.model.names)
        points = float(self.model.risk_points([x])[0])
        baseline, parts = self.model.contributions(x)
        # All contributions, unrounded, so baseline + sum == risk_points exactly (UIs round for display).
        contribs = sorted((Contribution(signal=n, label=LABEL[n], points=p) for n, p in parts.items()),
                          key=lambda c: -abs(c.points))
        level, reasons = level_for(points, self.levels, sig)
        return RiskDecision(
            step=step, tool=tool, level=level, decision=LEVEL_DECISION[level],  # type: ignore[arg-type]
            risk_points=points, probability=float(self.model.probability_from_points(points)),
            baseline_points=baseline, contributions=contribs, policy_rule=sig.policy_rule,
            llm_reason=sig.llm_reason, signal_errors=list(sig.errors), reasons=reasons,
            recommended_response=recommended_response(level, contribs),
        )
